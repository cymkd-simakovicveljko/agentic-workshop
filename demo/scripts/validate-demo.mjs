import {mkdtemp,cp,readFile,writeFile,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
const source=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=await mkdtemp(path.join(tmpdir(),'engineering-demo-'));
await cp(source,temp,{recursive:true,filter:p=>!p.includes(`${path.sep}node_modules`)&&!p.includes(`${path.sep}.runs`)});
const records=[];const start=performance.now();
function run(args,expected=0){const r=spawnSync(process.execPath,args,{cwd:temp,encoding:'utf8',timeout:30000});
 records.push({command:['node',...args].join(' '),exit:r.status,output:(r.stdout||'')+(r.stderr||'')});
 assert.equal(r.status,expected,records.at(-1).output);return records.at(-1).output;}
run(['scripts/preflight.mjs']);
run(['scripts/checkpoint.mjs','starter']);run(['--test','tests/baseline.test.mjs']);
run(['--test','tests/filter.test.mjs'],1);
run(['scripts/checkpoint.mjs','broken']);run(['scripts/harness.mjs','begin']);
const fail=run(['scripts/harness.mjs','check'],1);
assert.match(fail,/not ok.*trims surrounding spaces/);assert.match(fail,/# fail 2/);
run(['scripts/harness.mjs','check'],1);run(['scripts/harness.mjs','check'],3);
assert.equal(JSON.parse(await readFile(path.join(temp,'.runs/progress.json'))).status,'stopped-budget');
run(['scripts/harness.mjs','begin']);run(['scripts/checkpoint.mjs','solution']);
const pass=run(['scripts/harness.mjs','check']);assert.match(pass,/# pass 11/);
assert.equal(JSON.parse(await readFile(path.join(temp,'.runs/progress.json'))).humanAccepted,false);
// Reproduce interruption recovery through saved-state injection, not an actual killed process.
const statePath=path.join(temp,'.runs/progress.json');const s=JSON.parse(await readFile(statePath));s.status='running-check';await writeFile(statePath,JSON.stringify(s));
run(['scripts/harness.mjs','check'],3);assert.equal(JSON.parse(await readFile(statePath)).status,'interrupted');
run(['scripts/harness.mjs','begin']);run(['scripts/harness.mjs','check']);
const report={date:new Date().toISOString(),node:process.version,platform:process.platform,seconds:(performance.now()-start)/1000,temp,records};
await mkdir(path.join(source,'validation'),{recursive:true});
await writeFile(path.join(source,'validation/execution.json'),JSON.stringify(report,null,2));
console.log(`Validated starter, expected regression, two whitespace failures, repeat-stop and solution (11 tests). ${report.seconds.toFixed(2)} seconds of automated execution. Not a 30-minute presenter rehearsal.\nIsolated working copy: ${temp}`);
